-- ============================================
-- 1. BRANCHES
-- ============================================

CREATE TABLE branches
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    school_id  BIGINT       NOT NULL,

    name       VARCHAR(150) NOT NULL,
    code       VARCHAR(30)  NOT NULL,
    address    VARCHAR(500),

    active     BOOLEAN      NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_branches_school
        FOREIGN KEY (school_id)
            REFERENCES schools (id),

    CONSTRAINT uk_branches_school_name
        UNIQUE (school_id, name),

    CONSTRAINT uk_branches_school_code
        UNIQUE (school_id, code)
);


-- ============================================
-- 2. ROLES
-- ============================================

CREATE TABLE roles
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name        VARCHAR(50) NOT NULL UNIQUE,

    description VARCHAR(255)
);


-- ============================================
-- 3. USERS
-- ============================================

CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    full_name     VARCHAR(150) NOT NULL,

    email         VARCHAR(254) NOT NULL UNIQUE,

    password_hash VARCHAR(255) NOT NULL,

    active        BOOLEAN      NOT NULL DEFAULT TRUE,

    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================
-- 4. USER_ROLES (Many-to-Many)
-- ============================================

CREATE TABLE user_roles
(
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,

    PRIMARY KEY (user_id, role_id),

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id)
            REFERENCES users (id)
            ON DELETE CASCADE,

    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id)
            REFERENCES roles (id)
            ON DELETE CASCADE
);


-- ============================================
-- 5. USER_BRANCHES (Many-to-Many)
-- ============================================

CREATE TABLE user_branches
(
    user_id     BIGINT    NOT NULL,
    branch_id   BIGINT    NOT NULL,

    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id, branch_id),

    CONSTRAINT fk_user_branches_user
        FOREIGN KEY (user_id)
            REFERENCES users (id)
            ON DELETE CASCADE,

    CONSTRAINT fk_user_branches_branch
        FOREIGN KEY (branch_id)
            REFERENCES branches (id)
            ON DELETE CASCADE
);


-- ============================================
-- 6. INDEXES
-- ============================================

CREATE INDEX idx_branches_school_id
    ON branches (school_id);

CREATE INDEX idx_user_roles_role_id
    ON user_roles (role_id);

CREATE INDEX idx_user_branches_branch_id
    ON user_branches (branch_id);


